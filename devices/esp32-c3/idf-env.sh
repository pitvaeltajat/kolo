#!/usr/bin/env bash
# idf-env.sh — put the ESP-IDF toolchain on PATH for the current shell.
#
# Normally loaded automatically by direnv (see the workspace .envrc), but safe
# to source by hand:
#
#     source devices/esp32-c3/idf-env.sh
#
# ESP-IDF's own export.sh takes ~6 s, so its result is cached in
# ~/.cache/kolo/idf-env.sh and only rebuilt when export.sh changes (e.g. after
# `git pull` in the ESP-IDF checkout). Override the checkout with IDF_ROOT.

_idf_env_sourced=0
if [ -n "${BASH_SOURCE[0]:-}" ] && [ "${BASH_SOURCE[0]}" != "${0}" ]; then
  _idf_env_sourced=1
fi

# Rebuild the cache by running export.sh in a throwaway subshell and recording
# only the variables it actually changed.
_idf_env_build_cache() {
  local root="$1" cache="$2" tmp status

  if ! command -v python3 >/dev/null 2>&1; then
    printf 'idf-env: python3 is required to build the environment cache\n' >&2
    return 1
  fi

  tmp="$(mktemp -d)" || return 1

  (
    cd "$root" || exit 1
    env -0 >"$tmp/before"
    # shellcheck disable=SC1091
    . ./export.sh >/dev/null 2>&1 || exit 1
    env -0 >"$tmp/after"
  ) || {
    rm -rf "$tmp"
    printf 'idf-env: %s/export.sh failed\n' "$root" >&2
    return 1
  }

  python3 - "$tmp/before" "$tmp/after" "$cache" "$root" <<'PY'
import shlex
import sys

before_path, after_path, out_path, root = sys.argv[1:5]


def load(path):
    with open(path, "rb") as handle:
        data = handle.read()
    env = {}
    for chunk in data.split(b"\0"):
        if not chunk:
            continue
        name, _, value = chunk.partition(b"=")
        env[name.decode()] = value.decode("utf-8", "surrogateescape")
    return env


before = load(before_path)
after = load(after_path)

# Shell bookkeeping that must never be baked into the cache.
skip = {
    "PWD", "OLDPWD", "SHLVL", "_", "PATH", "PS1", "PS2", "PS4", "IFS",
    "BASH", "BASHOPTS", "BASHPID", "BASH_ALIASES", "BASH_ARGC", "BASH_ARGV",
    "BASH_ARGV0", "BASH_CMDS", "BASH_COMMAND", "BASH_LINENO", "BASH_SOURCE",
    "BASH_SUBSHELL", "BASH_VERSINFO", "BASH_VERSION", "COLUMNS", "LINES",
    "COMP_WORDBREAKS", "DIRSTACK", "EUID", "FUNCNAME", "GROUPS", "HISTCMD",
    "HOSTNAME", "HOSTTYPE", "LINENO", "MACHTYPE", "OPTERR", "OPTIND",
    "OSTYPE", "PIPESTATUS", "PPID", "RANDOM", "SECONDS", "SHELLOPTS",
    "SRANDOM", "UID",
}

lines = [
    "# Generated by devices/esp32-c3/idf-env.sh — do not edit.",
    "# idf-env cache for %s" % root,
]

for name in sorted(after):
    if name in skip or name.startswith("BASH_FUNC_"):
        continue
    if before.get(name) == after[name]:
        continue
    lines.append("export %s=%s" % (name, shlex.quote(after[name])))

# PATH is handled separately so that later PATH changes (venvs, nvm, ...) are
# preserved instead of being reset to whatever PATH looked like at build time.
before_dirs = before.get("PATH", "").split(":")
added = [d for d in after.get("PATH", "").split(":") if d and d not in before_dirs]
lines.append("IDF_PATH_ADDITIONS=%s" % shlex.quote(":".join(added)))

with open(out_path, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines) + "\n")
PY

  status=$?
  rm -rf "$tmp"
  return $status
}

# Prepend the ESP-IDF directories without duplicating entries already on PATH.
_idf_env_prepend_path() {
  local dir prefix=""

  [ -n "${IDF_PATH_ADDITIONS:-}" ] || return 0

  local IFS=:
  for dir in $IDF_PATH_ADDITIONS; do
    case ":$PATH:" in
      *":$dir:"*) continue ;;
    esac
    prefix="$prefix:$dir"
  done

  if [ -n "$prefix" ]; then
    PATH="${prefix#:}:$PATH"
    export PATH
  fi
}

_idf_env_load() {
  local root="${IDF_ROOT:-$HOME/esp/esp-idf}"
  local cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/kolo"
  local cache="$cache_dir/idf-env.sh"

  if [ ! -f "$root/export.sh" ]; then
    printf 'idf-env: ESP-IDF not found at %s (set IDF_ROOT to override)\n' "$root" >&2
    return 1
  fi

  # Already active in this shell — nothing to do.
  if [ "${IDF_PATH:-}" = "$root" ] && command -v idf.py >/dev/null 2>&1; then
    return 0
  fi

  if [ ! -f "$cache" ] ||
    [ "$root/export.sh" -nt "$cache" ] ||
    ! grep -qxF "# idf-env cache for $root" "$cache" 2>/dev/null; then
    mkdir -p "$cache_dir" || return 1
    _idf_env_build_cache "$root" "$cache" || return 1
  fi

  # shellcheck disable=SC1090
  . "$cache" || return 1

  _idf_env_prepend_path
  return 0
}

_idf_env_load
_idf_env_status=$?

if [ "$_idf_env_sourced" = 1 ]; then
  return "$_idf_env_status"
else
  exit "$_idf_env_status"
fi
